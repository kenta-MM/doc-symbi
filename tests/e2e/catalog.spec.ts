import { expect, test } from '../helpers/folder-page';

test('create in a real nested folder, combine filters, edit metadata and return through breadcrumbs', async ({ page }) => {
  await expect(page.getByRole('region', { name: 'ドキュメント一覧' })).toBeVisible();
  for (const name of ['EC', '詳細設計書', '認証']) {
    await page.getByRole('button', { name: '選択中のフォルダの作成メニュー' }).click();
    await page.getByRole('menuitem', { name: 'フォルダを作成' }).click();
    await page.getByLabel('フォルダ名', { exact: true }).fill(name);
    await page.getByRole('button', { name: '実行', exact: true }).click();
    await expect(page.getByRole('dialog')).toHaveCount(0);
    await page.getByRole('navigation', { name: 'フォルダ階層' }).getByRole('button', { name: `▱ ${name}`, exact: true }).click();
  }
  await page.getByRole('button', { name: '新規作成', exact: true }).click();
  await page.getByLabel('新しいドキュメント名').fill('ログイン処理');
  await page.getByLabel('ドキュメント種類', { exact: true }).selectOption('detailed-design');
  await page.getByLabel('タグ', { exact: true }).fill('認証, API');
  await page.getByRole('button', { name: '作成して編集を開始' }).click();
  await expect(page.getByRole('status')).toContainText('保存済み');
  await page.locator('.tiptap').fill('トークンの有効期限を検証する');
  await page.keyboard.press('Control+s');
  await expect(page.getByRole('status')).toContainText('保存済み');
  await page.getByRole('navigation', { name: 'パンくずリスト' }).getByRole('button', { name: '詳細設計書', exact: true }).click();
  await expect(page.locator('.document-link')).toHaveText(['ログイン処理']);
  await page.getByLabel('文書を検索').fill('有効期限');
  await page.getByLabel('種類で絞り込み').selectOption('detailed-design');
  await page.getByLabel('タグで絞り込み').selectOption('API');
  await expect(page.locator('.document-link')).toHaveCount(1);
  await page.getByLabel('子孫フォルダを含む').uncheck();
  await expect(page.locator('.document-link')).toHaveCount(0);
  await page.getByLabel('子孫フォルダを含む').check();
  await page.getByLabel('文書を検索').fill('EC/詳細設計書/');
  await expect(page.locator('.document-link')).toHaveCount(1);
  await page.getByLabel('文書を検索').fill('別/詳細設計書/');
  await expect(page.locator('.document-link')).toHaveCount(0);
  await page.getByLabel('文書を検索').fill('EC/詳細設計書/');
  await page.locator('.document-link').dblclick();
  await expect(page.locator('.tiptap')).toHaveAttribute('contenteditable', 'false');
  await page.getByRole('button', { name: '編集', exact: true }).click();
  await page.getByLabel('ドキュメントのステータス').selectOption('review');
  await page.getByLabel('ドキュメントのタグ').fill('認証, セキュリティ');
  await page.getByLabel('ドキュメントのタグ').press('Control+s');
  await expect(page.getByRole('status')).toContainText('保存済み');
  await page.reload();
  await expect(page.getByLabel('ドキュメントのステータス')).toHaveValue('review');
  await expect(page.locator('.document-properties')).toContainText('セキュリティ');
  await page.getByRole('button', { name: '情報を閉じる' }).click();
  await expect(page.locator('.document-properties')).toHaveCount(0);
  await page.goto('/');
  await expect(page.getByRole('region', { name: 'ドキュメント一覧' })).toBeVisible();
  const ec = page.getByRole('button', { name: '▱ EC', exact: true });
  await ec.click();
  await expect(ec).toHaveAttribute('aria-current', 'page');
  await expect(ec).toHaveAttribute('aria-expanded', 'true');
  await ec.click();
  await expect(ec).toHaveAttribute('aria-expanded', 'false');
  await page.getByRole('button', { name: '▱ articles', exact: true }).click();
  await ec.click();
  await expect(ec).toHaveAttribute('aria-expanded', 'false');
  await expect(page.getByRole('navigation', { name: 'フォルダ階層' }).getByRole('button', { name: '▱ 認証', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: '▱ EC', exact: true }).click();
  await expect(page.getByRole('navigation', { name: 'フォルダ階層' }).getByRole('button', { name: '▱ 認証', exact: true })).toBeVisible();
  await page.screenshot({ path: 'test-results/catalog-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  await page.screenshot({ path: 'test-results/catalog-mobile.png' });
  await page.getByRole('button', { name: '新規作成', exact: true }).click();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: 'test-results/create-desktop.png' });
});
