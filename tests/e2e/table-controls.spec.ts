import { expect, test } from '../helpers/folder-page';

test('table context copy pastes a full independent table at the cursor and delete is undoable', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write']);
  await page.getByRole('button', { name: '新規作成', exact: true }).click();
  await page.getByRole('button', { name: '作成して編集を開始', exact: true }).click();
  const body = page.locator('.tiptap');
  await body.click(); await body.pressSequentially('before after');
  await body.press('Enter');
  await page.getByRole('button', { name: '表を挿入' }).click();
  await page.getByRole('button', { name: '挿入', exact: true }).click();
  await body.locator('table th p').first().click(); await page.keyboard.type('見出し');
  await body.locator('table td p').first().click(); await page.keyboard.type('セル内容');
  await expect(body.locator('table th').first()).toHaveText('見出し');
  await expect(body.locator('table td').first()).toHaveText('セル内容');
  await body.locator('table td').first().click({ button: 'right' });
  await page.getByRole('menuitem', { name: '表のコピー', exact: true }).click();
  // Wait until the real system clipboard write finishes before issuing paste.
  await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toContain('セル内容');
  await body.locator(':scope > p').first().click();
  await body.locator(':scope > p').first().evaluate(node => window.getSelection()!.collapse(node.firstChild!, 7));
  await body.press('Control+v');
  await expect(body.locator('table')).toHaveCount(2);
  await expect(body.locator('table').first().locator('th').first()).toHaveText('見出し');
  await expect(body.locator('table').first().locator('td').first()).toHaveText('セル内容');
  await expect(body.locator(':scope > p').first()).toHaveText('before ');
  await expect(body.locator(':scope > p').nth(1)).toHaveText('after');
  await body.locator('table').first().locator('td p').first().fill('コピーを編集');
  await expect(body.locator('table').last().locator('td').first()).toHaveText('セル内容');
  await body.locator('table').first().locator('td').first().click({ button: 'right' });
  await page.getByRole('menuitem', { name: '表の削除', exact: true }).click();
  await expect(body.locator('table')).toHaveCount(1);
  await body.press('Control+z'); await expect(body.locator('table')).toHaveCount(2);
  await expect(body.locator('table').first()).toContainText('コピーを編集');
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await expect(page.getByRole('status', { name: '保存状態' })).toContainText('保存済み');
  await page.reload();
  await expect(body.locator('table')).toHaveCount(2);
  await expect(body.locator('table').first()).toContainText('コピーを編集');
});

test('table context targets and resizing persist', async ({ page }) => {
  await page.getByRole('button', { name: '新規作成', exact: true }).click();
  await page.getByRole('button', { name: '作成して編集を開始', exact: true }).click();
  await page.getByRole('button', { name: '表を挿入' }).click();
  await page.getByRole('button', { name: '挿入', exact: true }).click();
  const rows = page.locator('.tiptap tr');
  await rows.nth(1).locator('p').nth(1).click(); await page.keyboard.type('対象');
  await rows.nth(2).locator('p').nth(2).click(); await page.keyboard.type('残す');
  await expect(rows.nth(1)).toContainText('対象');
  await expect(rows.nth(2)).toContainText('残す');
  await rows.nth(1).locator('td').nth(1).click({ button: 'right' });
  await page.getByRole('menuitem', { name: '行を追加（下）', exact: true }).click();
  await expect(rows).toHaveCount(4);
  await expect(rows.nth(1)).toContainText('対象');
  await expect(rows.nth(2)).toHaveText('');
  await expect(rows.nth(3)).toContainText('残す');
  await rows.nth(1).locator('td').nth(1).click({ button: 'right' });
  await page.getByRole('menuitem', { name: '列を追加（右）', exact: true }).click();
  await expect(rows.nth(1).locator('td')).toHaveCount(4);
  await expect(rows.nth(3).locator('td').nth(3)).toHaveText('残す');
  await rows.nth(1).locator('td').nth(1).click({ button: 'right' });
  await page.getByRole('menuitem', { name: '行を削除', exact: true }).click();
  await expect(rows).toHaveCount(3);
  await expect(page.locator('.tiptap table')).not.toContainText('対象');
  await rows.nth(2).locator('td').nth(3).click({ button: 'right' });
  await page.getByRole('menuitem', { name: '列を削除', exact: true }).click();
  await expect(rows.nth(2).locator('td')).toHaveCount(3);
  await expect(page.locator('.tiptap table')).not.toContainText('残す');
  const handle = page.getByRole('button', { name: '表サイズ変更（右下）' });
  await handle.scrollIntoViewIfNeeded();
  const before = (await page.locator('.tiptap table').boundingBox())!;
  const box = (await handle.boundingBox())!;
  await page.mouse.move(box.x + 7, box.y + 7);
  await page.mouse.down();
  await page.mouse.move(box.x - 193, box.y + 67, { steps: 5 });
  await page.mouse.up();
  const frame = page.locator('.table-resize-frame');
  await expect(frame).toHaveCSS('width', `${Math.round(before.width - 200)}px`);
  const style = await frame.getAttribute('style');
  await page.keyboard.press('Control+z');
  await expect(frame).not.toHaveAttribute('style', style!);
  await page.keyboard.press('Control+y');
  await expect(frame).toHaveAttribute('style', style!);
  await rows.nth(1).locator('p').first().fill('編集確認');
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: '保存済み' })).toBeVisible();
  await page.reload();
  await expect(frame).toHaveAttribute('style', style!);
  await expect(frame).toContainText('編集確認');
  await expect(handle).toBeHidden();
});
