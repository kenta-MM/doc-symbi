import { expect, test } from '../helpers/folder-page';
import { fixtureDocument } from '../fixtures/documents';

test('AI panel keeps drafts by document and provider and supports narrow screens', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto('/tests/harness.html');
  await page.evaluate(async text => { await window.createFileRepositoryTest().create(JSON.parse(text)); }, JSON.stringify(fixtureDocument()));
  await page.goto('/');
  await expect(page.locator('#ai-side-panel')).toBeHidden();
  await page.getByRole('button', { name: 'AIチャット', exact: true }).click();
  const input = page.getByRole('textbox', { name: 'AIへの依頼' });
  await expect(page.locator('.ai-chat-context, .ai-welcome-mark')).toHaveCount(0);
  await expect(page.getByRole('heading', { name: '文書づくりを、AIと一緒に' })).toBeVisible();
  await expect(page.locator('.ai-suggestions')).toHaveCount(0);
  expect((await page.locator('#ai-side-panel').boundingBox())!.width).toBeCloseTo(254, 0);
  await input.fill('新人向けの導入ガイドを作って');
  await expect(input).toHaveValue('新人向けの導入ガイドを作って');
  await page.getByRole('button', { name: 'サイドパネルを閉じる' }).click();
  await expect(input).toBeHidden();
  await page.getByRole('button', { name: 'AIチャット', exact: true }).click();
  await expect(input).toHaveValue('新人向けの導入ガイドを作って');
  await page.getByRole('button', { name: '設定', exact: true }).click();
  await page.getByLabel('利用するAI').selectOption('claude');
  await page.getByRole('dialog', { name: '設定', exact: true }).getByRole('button', { name: '保存', exact: true }).click();
  await page.getByRole('button', { name: '設定を閉じる' }).click();
  await expect(input).toHaveValue('');
  await input.fill('Claudeへの下書き');
  await page.getByRole('button', { name: '設定', exact: true }).click();
  await page.getByLabel('利用するAI').selectOption('codex');
  await page.getByRole('dialog', { name: '設定', exact: true }).getByRole('button', { name: '保存', exact: true }).click();
  await page.getByRole('button', { name: '設定を閉じる' }).click();
  await expect(input).toHaveValue('新人向けの導入ガイドを作って');
  await page.locator('.catalog-table .document-link').dblclick();
  await expect(input).toHaveValue('');
  await expect(page.locator('.ai-suggestions')).toHaveCount(0);
  await input.fill('この文書を要約して');
  await page.getByRole('tab', { name: '文書情報', exact: true }).click();
  await expect(page.getByRole('complementary', { name: 'ドキュメント情報', exact: true })).toBeVisible();
  await page.getByRole('tab', { name: '文書情報', exact: true }).press('ArrowLeft');
  await expect(input).toHaveValue('この文書を要約して');
  await expect(page.getByRole('button', { name: 'AIに送信', exact: true })).toBeDisabled();
  const panel = page.locator('#ai-side-panel');
  const before = (await panel.boundingBox())!.width;
  await page.getByRole('separator', { name: 'AIチャットの幅' }).press('ArrowLeft');
  expect((await panel.boundingBox())!.width).toBeCloseTo(before + 10, 0);
  await page.screenshot({ path: 'test-results/ai-chat-desktop.png' });
  await page.setViewportSize({ width: 390, height: 760 });
  await expect(input).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  await page.screenshot({ path: 'test-results/ai-chat-mobile.png' });
  await page.getByRole('button', { name: 'サイドパネルを閉じる' }).click();
  await expect(page.locator('.document-canvas')).toBeVisible();
  await page.getByRole('button', { name: 'AIチャット', exact: true }).click();
  await page.getByRole('button', { name: '設定', exact: true }).click();
  await page.getByLabel('利用するAI').selectOption('claude');
  await page.getByRole('dialog', { name: '設定', exact: true }).getByRole('button', { name: '保存', exact: true }).click();
  await page.getByRole('button', { name: '設定を閉じる' }).click();
  await page.reload();
  await expect(page.locator('#ai-side-panel')).toBeHidden();
  await expect(page.getByRole('button', { name: 'AIチャット', exact: true })).toHaveAttribute('aria-expanded', 'false');
  await page.getByRole('button', { name: 'AIチャット', exact: true }).click();
  await expect(page.getByText('Claude連携は準備中です', { exact: true })).toBeVisible();
});
